#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES.md from the modules linked into the binary.
#
# pinboard-checker statically links a BSD-3-Clause dependency (golang.org/x/net),
# and BSD-3 clause 2 attaches conditions to *binary*
# redistribution: the copyright notice and disclaimer must accompany the
# distribution. Shipping only the project's own MIT LICENSE does not satisfy it.
#
# GoReleaser runs this as a `before` hook, so every release ships notices for
# exactly the modules in the tagged go.mod. The file is not tracked: a committed
# copy went stale with every dependency bump nobody regenerated it for.
#
# `go list -deps` walks the main package's imports, so test-only modules are
# correctly excluded -- they are not in the shipped binary.
#
# Lives as a script rather than an inline hook or mise task because the go list
# format string is full of {{...}}, which both would try to interpolate.
set -euo pipefail

cd "$(dirname "$0")/.."

out=THIRD_PARTY_NOTICES.md
module=$(go list -m)

{
  echo "# Third-Party Notices"
  echo
  echo "\`pinboard-checker\` statically links the Go modules below. Their license"
  echo "terms require that these notices accompany binary distributions."
  echo
  echo "Generated by \`scripts/gen-notices.sh\` at release time — do not edit by hand."
} >"$out"

go list -deps -f '{{with .Module}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}' . |
  sort -u |
  while IFS=$'\t' read -r path version dir; do
    [ -n "${dir:-}" ] || continue
    [ "$path" != "$module" ] || continue
    # A module whose license file has none of these names fails the run -- a
    # silently missing notice is the defect this prevents. When a new
    # dependency trips it, add that module's file name here.
    found=0
    for f in LICENSE LICENSE.txt LICENSE.md COPYING NOTICE; do
      [ -f "$dir/$f" ] || continue
      found=1
      # The filename goes in the heading, not a subheading: a module shipping
      # both LICENSE and NOTICE would otherwise emit the same heading twice and
      # trip markdownlint MD024. ```text, not a bare fence, for MD040.
      {
        printf '\n## %s %s — %s\n\n```text\n' "$path" "$version" "$f"
        cat "$dir/$f"
        printf '```\n'
      } >>"$out"
    done
    if [ "$found" -eq 0 ]; then
      printf 'gen-notices: no license file for %s %s\n' "$path" "$version" >&2
      exit 1
    fi
  done

printf 'wrote %s (%s modules)\n' "$out" "$(grep -c '^## ' "$out")"
